//  🔴 **왜 생겼나.** 375px 에서 Sync 표(5열)의 마지막 칸 「마지막 보고」가 오른쪽에서
//    글자 중간에 잘렸다. 데이터를 잃은 것은 아니다 — 바깥은 `.scroll-x`(overflow-x: auto)라
//    손가락으로 밀면 나온다. 문제는 **밀 수 있다는 신호가 아무 데도 없다**는 것이다.
//    휴대폰에는 스크롤 막대가 평소 안 보이므로, 처음 보는 사람 눈에는 그냥 **잘린 표** —
//    즉 고장 난 화면이다. 온라인 투표가 20% 인 대회에서 그건 비싼 오해다.
//
//  ★ 왜 그라데이션(페이드)이 아니라 글자인가 — DESIGN_BRIEF §6 이 그림자·그라데이션을
//    금지한다. 그리고 이 저장소는 애매하면 **사람 말 한 줄**로 말해 왔다.
//  ★ 왜 표 아래인가 — 위에 두면 넓은 화면에서도 읽히는 자리를 먹는다. 헷갈린 사람은
//    표 언저리를 훑는다. 좁은 폭에서만 나오고 (`globals.css` 의 유일한 폭 질의),
//    넓은 화면에서는 **아예 안 그려진다**.
//
//  ⚠ 이 부품은 **표에만** 쓴다. `.scroll-x` 는 `<pre>`·`<code>`·내비에도 붙어 있는데
//    거기엔 이 안내가 거짓말이다 (그 자리들은 밀어도 볼 것이 없거나 줄바꿈으로 접힌다).
//  ⚠ 좁은 폭에서 표를 **행 카드로 쌓는 것**이 더 나은 답이다. 안 한 이유는 표마다
//    마크업이 따로라(`sync`·`versions`·`proposals`) 한 번에 못 바꾸기 때문이다.
//    그 리팩터를 하는 바퀴에 이 부품이 그 자리가 된다 — 감싸는 자리가 이미 하나다.
// =====================================================================

/** 좁은 폭에서만 보이는 안내. ⚠ 문구를 화면마다 적지 마라 — 여기 한 곳이다. */
export const SCROLL_TABLE_HINT = '표가 화면보다 넓습니다 — 옆으로 밀어 보세요'

export function ScrollTable({ children }: { children: ReactNode }) {
  return (
    <>
      <div className="scroll-x">{children}</div>
      {/* `aria-hidden` 이 아니다 — 스크린 리더로 읽는 사람에게도 표가 넓다는 사실은 참이다. */}
      <p className="meta scroll-table-hint">{SCROLL_TABLE_HINT}</p>
    </>
  )
}
