/** 프로젝트 화면의 첫 문장 — 팀 이름을 낫표로 싼다. 「{이름} 팀에」는 이름이 「결제팀」이면 「결제팀 팀에」가 됐다. */
export function projectWhere(teamName: string): string {
  return `「${teamName}」에 만듭니다.`
}

/**
 * 「1 팀 → 2 프로젝트 → 3 첫 문서」 — **지금 걸음만 굵다.** 숫자가 곧 차례라 번호를 붙인다.
 * ⚠ 훅이 없다 — 시험이 브라우저 없이 그린다.
 */
export function SetupSteps({ current }: { current: SetupStepIndex }) {
  return (
    <p className="meta">
      {SETUP_STEPS.map((step, i) => (
        <Fragment key={step}>
          {i > 0 ? ' → ' : null}
          {i === current ? <b className="ink">{`${i + 1} ${step}`}</b> : `${i + 1} ${step}`}
        </Fragment>
      ))}
    </p>
  )
}
