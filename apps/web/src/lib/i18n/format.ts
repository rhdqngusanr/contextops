//  🔴 **왜 함수가 아니라 자리표시자인가** — 문구를 `(on) => \`마지막 갱신 ${on}\`` 처럼
//     함수로 두면 편하다. 그런데 그러면 **게이트(`test/i18n.test.ts`)가 그 문장을 못 본다** —
//     함수는 속을 열 수 없어서 「영어 쪽에 한글이 남았나」 검사를 그냥 지나간다.
//     실제로 `/privacy` 를 고치다 그 자리를 만들 뻔했고, 그래서 이 파일이 생겼다.
//     지금은 값이 **문자열**이라 게이트가 읽고, 시험도 문장을 그대로 견줄 수 있다.
//
//  ★ 왜 낱말이 있는 자리표시자(`{on}`)인가 — 번호(`{0}`)로 두면 언어마다 **어순이 달라질 때**
//    무엇이 들어가는 자리인지 알 수가 없다. 한국어는 「마지막 갱신 {on}」이고 영어는
//    「Last updated {on}」처럼 자리가 옮겨 다닌다.
//
//  ⚠ 채울 값이 없으면 자리표시자를 **그대로 남긴다.** 조용히 빈칸으로 만들면 「마지막 갱신 」
//    같은 문장이 화면에 나가고, 그게 왜 비었는지 아무 데도 안 적힌다.
// =====================================================================

/** `{이름}` 자리에 값을 끼운다. 없는 이름은 그대로 남는다 (위 ⚠). */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
    (Object.hasOwn(values, key) ? String(values[key]) : whole))
}
