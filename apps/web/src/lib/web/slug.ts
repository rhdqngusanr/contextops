// =====================================================================
//  이름 → slug 후보 (SPEC §5 `CreateTeam`·`CreateProject` 의 `slug` 규칙)
//
//  ★ 왜 따로 있나 — 팀 만들기와 프로젝트 만들기 **둘 다** 쓴다. 화면마다 적으면
//    한쪽만 규칙이 갈리고, 그 화면에서만 400 이 난다.
//
//  ⚠ 규칙의 정본은 `packages/schema` 의 `Slug` 다. 여기서는 **후보를 만들기만** 하고
//    맞는지는 서버가 판정한다 — 정규식을 두 곳에 적어 놓고 한쪽만 고치는 일을 막으려면
//    「만드는 쪽」과 「재는 쪽」이 갈라져 있어야 한다.
//
//  ⚠ 한글 이름은 후보가 **빈 문자열**이다. 억지로 음차하지 않는다 — 지어낸 slug 가
//    주소에 박히면 나중에 못 바꾼다. 비면 사람이 직접 적는다 (칸은 편집 가능하다).
// =====================================================================

export function toSlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
    .replace(/-+$/g, '')
}
