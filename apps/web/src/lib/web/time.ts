// =====================================================================
//  「마지막 보고: 8분 전」 — 시각을 사람의 말로 (DESIGN_BRIEF §2-3)
//
//  🔴 **「실시간」이라는 낱말을 쓰지 않는다.** 이 제품이 말할 수 있는 것은 언제나
//     「마지막으로 본 것이 언제인가」다. 그래서 화면에는 절대 시각이 아니라 **경과**가
//     나가고, 그 경과를 만드는 자리가 여기 하나다.
//
//  ★ 왜 파일 하나인가 — 화면마다 `Math.floor((now - t) / 60000) + '분 전'` 을 적으면
//    어느 화면은 「0분 전」을 그리고 어느 화면은 「-1분 전」을 그린다 (서버 시계가
//    브라우저보다 조금 앞설 때 실제로 그렇게 된다). 순수 함수라 시험이 잰다.
//
//  ⚠ 절대 시각이 필요한 자리(발행 시각 같은 것)에 쓰지 마라 — 그건 「언제 있었나」이지
//    「얼마나 됐나」가 아니다. 버전 히스토리는 지금도 `2026-09-04 12:18` 을 그대로 쓴다.
// =====================================================================

/**
 * 단위의 표 — **큰 것부터** 본다. 첫 줄이 「그 아래는 전부 방금」의 잣대다.
 * ★ 단위를 더하려면 여기 한 줄. 화면은 이 표를 모른다.
 */
const UNITS: { seconds: number; label: string }[] = [
  { seconds: 86400, label: '일' },
  { seconds: 3600, label: '시간' },
  { seconds: 60, label: '분' },
]

/** 1분이 안 됐을 때의 말. 「0분 전」이라고 쓰지 않는다 — 그건 시각이 아니라 반올림이다. */
export const JUST_NOW = '방금'

/**
 * `2026-09-04T12:18:58Z` → `8분 전`.
 *
 * ⚠ 미래(서버 시계가 앞선 경우)도 `방금`이다. 「-3분 전」은 사람에게 아무 뜻이 없고,
 *   그 한 줄 때문에 화면이 고장난 것처럼 보인다 (경과는 늘 0 이상이다).
 */
export function sinceText(iso: string, now: Date = new Date()): string {
  const elapsed = (now.getTime() - Date.parse(iso)) / 1000
  if (!Number.isFinite(elapsed)) return JUST_NOW
  for (const unit of UNITS) {
    if (elapsed >= unit.seconds) return `${Math.floor(elapsed / unit.seconds)}${unit.label} 전`
  }
  return JUST_NOW
}
