# =====================================================================
#  loop/env.ps1 — 자율 개발 루프 설정. 로직은 없다, 값만 산다.
#
#  ⚠ Claude Code CLI 에 --max-turns 가 없다. 그래서 한 바퀴는 "턴 수" 가 아니라
#    **시간**으로 자른다. 실제 턴 수와 비용은 stream-json 결과의 num_turns /
#    total_cost_usd 로 사후에 재고, 그걸 보고 아래 값을 조정한다.
#
#  값을 바꿨으면 **왜 바꿨는지 한 줄** 남겨라. 다음 사람(과 다음 바퀴)이 읽는다.
# =====================================================================

$LOOP = @{

    # ── 모델 ──────────────────────────────────────────────────────
    #  전체 이름으로 박는다. 별칭("opus")은 최신 것을 따라가므로 **어느 날 갑자기
    #  다른 모델로 도는데 로그만 봐서는 모른다.**
    Model = "claude-opus-5"

    #  추론 노력 (low | medium | high | xhigh | max — CLI `--effort`).
    #  ★ 왜 high 인가 — ContextOps 의 한 바퀴는 「화면 하나 예쁘게」가 아니라
    #    **스키마·컴파일러·발행 트랜잭션**처럼 틀리면 조용히 새는 일이다.
    #    한 바퀴가 싼 것보다 한 바퀴가 맞는 게 훨씬 싸다.
    #  ⚠ 높이면 한 바퀴가 비싸진다 — 주간 한도가 빠듯할 때 제일 먼저 되돌릴 값이다.
    Effort = "high"

    # claude.exe 절대경로. 작업 스케줄러는 PATH 를 안 물려받는다 —
    # 여기가 비면 **조용히 죽는다.** ctl.ps1 install 이 자동으로 찾아 채운다.
    ClaudeExe = "C:\nvm4w\nodejs\node_modules\@anthropic-ai\claude-code\bin\claude.exe"

    # ── 한 바퀴 ───────────────────────────────────────────────────
    #  우리 한 바퀴 = 문서 읽기 + TS 작성 + tools/ci.ps1(5층). Unity 왕복이 없어서
    #  rift 보다 짧다. 두 바퀴 시험 주행(ctl.ps1 dryrun) 로그의 duration 을 보고 확정해라.
    CycleTimeoutMin = 45

    SleepBetweenSec = 60

    # ── 멈추는 조건 (셋 중 먼저 오는 쪽) ──────────────────────────
    #  ★ **바퀴 수보다 바퀴당 비용이 진짜 제약이다.** rift 에서 배운 것이다 —
    #    주간 사용량이 92% 인 채로 60바퀴를 걸어 두면 8%를 태우고 나머지는
    #    실패 응답만 받는다. 그래서 여기엔 비용 상한이 같이 있다.
    #  한도에 걸리면 루프가 스스로 물러섰다가 다시 시도한다 (BackoffMin).
    MaxCycles  = 12
    MaxHours   = 12

    #  이번 실행에서 누적 total_cost_usd 가 이걸 넘으면 멈춘다. 0 이면 끄기.
    #  ⚠ CLI 가 결과 줄에 비용을 안 실어 주면(구독 플랜 등) 0 으로 누적되어
    #    사실상 꺼진 것과 같다 — 그때는 MaxCycles 가 유일한 울타리다.
    #
    #  🔴 2026-09-03 0 → 30 → 50 → **0 (끔)** (사용자 지시:
    #    *"어차피 구독계정에서빠지는거보니까 상한없애줘"*).
    #
    #    ★ 왜 껐나 — **구독 플랜이면 이 숫자는 실제 청구액이 아니라 환산값이다.**
    #      진짜 벽은 사용량 한도(주간·5시간)고, 거기 걸리면 이 상한이 아니라
    #      BackoffMin 이 작동한다 (20 → 40 → 80 → 120분, 그 바퀴는 세지 않는다).
    #      환산값으로 멈추면 **아직 쓸 수 있는데 스스로 문을 닫는** 셈이다.
    #      실제로 그랬다: 30 에 걸려 4바퀴에서 멈췄다 (17:08).
    #
    #    실측 이력 — 짐작이 아니라 잰 것만 적는다:
    #      · dryrun(읽고 판단만)  7턴 ·  24초 · $0.42
    #      · 실주행 바퀴 1        52턴 · 572초 · $4.02
    #      · 실주행 바퀴 2        93턴 · 1093초 · $9.07
    #      · 실주행 바퀴 3        92턴 · 1927초 · $13.90   ← 컴파일러 바퀴. 32분, 타임아웃 45분에 근접
    #      · 실주행 바퀴 4        46턴 ·  480초 · $3.05
    #      → 바퀴당 편차가 3배 넘게 난다. **평균으로 상한을 잡으면 반드시 어긋난다.**
    #
    #  ⚠ 껐다고 무한이 아니다. 남은 울타리 넷: MaxCycles(12) · MaxHours(12) ·
    #    IdleCyclesMax(3 연속 빈 바퀴) · STOP 파일. 지금은 **MaxCycles 가 먼저 닿는다**
    #    (바퀴 평균 20분 × 12 ≈ 4~5시간).
    #  ⚠ API 종량제로 돌릴 거면 **여기를 반드시 다시 켜라.** 그때는 환산값이 아니라 청구액이다.
    MaxCostUsd = 0

    # ── 브랜치 ────────────────────────────────────────────────────
    #  사람이 커밋 단위로 보고 있고 한 바퀴가 한 커밋이라, 골라내기가 이미 된다.
    #  ⚠ **여러 세션이 이 디렉터리를 같이 쓰거나 무인 야간으로 돌릴 거면**
    #    `loop/auto` 같은 별도 브랜치로 바꿔라 — 사람이 main 에서 손으로 작업 중일 때
    #    브랜치가 갈리면 발밑에서 파일이 바뀐다.
    Branch = "main"

    # ── 사전 점검 ─────────────────────────────────────────────────
    #  ★ rift 의 #1 조용한 실패가 「PATH 를 못 물려받아 git·node 를 못 찾고 죽는데
    #    로그에도 안 남는」 것이었다. 그래서 바퀴를 돌기 전에 **직접 불러 본다.**
    #    여기서 실패하면 일하지 않고 기다린다 — 못 만드는 채로 도는 것보다 낫다.
    PreflightCmds = @("git --version", "node --version")
    PreflightWaitSec = 120
    PreflightWaitMax = 10      # 이만큼 기다려도 안 되면 루프를 끝낸다

    # ── 조용한 실패 감지 ──────────────────────────────────────────
    #  ★ rift 의 최악 사고: 부트 프롬프트가 단어 단위로 쪼개져 세션이 할 일을 못 본 채
    #    "무엇을 도와드릴까요?" 라고 답하고 끝났다 (10초 · 1턴 · $0.24). 바퀴는 **OK 로
    #    기록되고** 아무것도 안 바뀐다. 에러가 안 나서 로그만 봐선 모른다.
    #  → 그래서 바퀴마다 **커밋이 늘었는지**를 센다. 연속으로 이만큼 아무 커밋도
    #    없으면 벽에 부딪힌 것으로 보고 멈춘다. 밤새 헛도는 것보다 낫다.
    IdleCyclesMax = 3

    # ── 사용량 한도 백오프 ────────────────────────────────────────
    #  한도에 걸린 뒤 그냥 돌면 실패 응답만 받으며 남은 밤을 버린다.
    BackoffMin    = 20
    BackoffMaxMin = 120
}

# 설치할 때 캡처해 둔 PATH 등. 있으면 덮어쓴다 (.gitignore 대상)
$__local = Join-Path $PSScriptRoot "env.local.ps1"
if (Test-Path $__local) { . $__local }
